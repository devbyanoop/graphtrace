"""`graphtrace from-trace`: turn a NormalizedTrace (importers/base.py) into a
cassette plus a generated pytest file that replays it.

The cassette entries this module writes use the "any" positional-match
convention `replay/engine.py` added specifically for this feature (see that
module's own comment) -- an imported trace's `request` field is whatever
shape the *source observability platform* exported (Langfuse JSON, OTel
attributes, ...), never the real `str(list[BaseMessage])` the live LangGraph
interceptor hashes at replay time. There is no general transformation between
those two, so exact request-hash matching (what every other cassette in this
project relies on) simply cannot work here -- matching by node/kind/occurrence
position only, trusting the target graph to walk the same path for the same
`initial_input`, is the honest alternative, not a shortcut.
"""

from __future__ import annotations

import importlib
import inspect
from pathlib import Path
from typing import Any

from jinja2 import Environment

from graphtrace.importers.base import NormalizedSpan, NormalizedTrace
from graphtrace.replay.cassette import Cassette, save_cassette

# A dedicated Environment, not the `Template(...)` convenience constructor --
# that one compiles its source immediately, before there's any chance to
# register the "pyrepr" filter it needs (confirmed by hand: doing it the other
# way round raises TemplateAssertionError: No filter named 'pyrepr').
_env = Environment()
_env.filters["pyrepr"] = repr
_TEST_TEMPLATE = _env.from_string(
    '''"""Generated by `graphtrace from-trace` -- replays a real, previously
observed run from a cassette.

The assertions below only confirm the nodes that were *actually* observed in
the source trace were visited, which is not necessarily the behaviour that
*should* happen -- fill in the TODO with what this run should really be held to.
"""

from graphtrace import assert_visited, run_graph
from {{ target_module }} import {{ target_factory }}


def test_{{ test_name }}():
{%- if needs_manual_construction %}
    graph = {{ target_factory }}(...)  # TODO: this factory takes required arguments graphtrace can't know from the trace alone (e.g. a chat model) -- construct it the way your app really does
{%- else %}
    graph = {{ target_factory }}()
{%- endif %}
    trajectory = run_graph(
        graph,
        {{ initial_input|pyrepr }},
        cassette={{ cassette_path|pyrepr }},
        mode="replay",
{%- if interrupted %}
        resume=[...],  # TODO: fill in what the human actually sent -- not recoverable from the source trace
{%- endif %}
    )

    # TODO: assert the correct behaviour, not just that these nodes ran. Only
    # visits are checked, not the exact path (assert_path) -- a node that makes
    # no LLM/tool call (a router's own branch, a plain interrupt point) is
    # invisible to every trace importer, so claiming to know the *exact* full
    # path from an imported trace would be a false promise. Tighten this by
    # hand with assert_path(...)/assert_tool_calls_match(...) once you know it.
{% for node in observed_nodes %}
    assert_visited(trajectory, {{ node|pyrepr }})
{%- endfor %}
'''
)


def _factory_needs_manual_construction(target_module: str, target_factory: str) -> bool:
    """Whether `{{ target_factory }}()` (no arguments) would actually be wrong
    for the real factory -- decided by importing it for real and inspecting its
    signature, not guessed. A builder function that takes a chat model (or other
    required config) as an argument is a completely ordinary, common shape for
    a LangGraph graph -- confirmed by this project's own refund_agent demo,
    `build_refund_graph(chat_model, ...)` -- so assuming every factory is
    zero-argument would silently generate a wrong call for exactly that case.

    An import failure (wrong --target, module not yet on the path, ...) is
    treated the same as "needs arguments": there's no way to know, and the
    generated test's own top-level `from ... import ...` line surfaces the
    real problem either way regardless of how this one call is rendered.
    """
    try:
        module = importlib.import_module(target_module)
        signature = inspect.signature(getattr(module, target_factory))
    except Exception:
        return True
    return any(
        param.default is inspect.Parameter.empty and param.kind not in (inspect.Parameter.VAR_POSITIONAL, inspect.Parameter.VAR_KEYWORD)
        for param in signature.parameters.values()
    )


def _split_target(target: str) -> tuple[str, str]:
    """"my_app.graph:build_graph" -> ("my_app.graph", "build_graph")."""
    module, _, factory = target.partition(":")
    if not factory:
        raise ValueError(f"target must be shaped 'module:factory', got {target!r}")
    return module, factory


def _normalize_llm_response(response: Any) -> dict[str, Any]:
    """Imported-trace LLM output -> the exact shape
    `frameworks/langgraph/interceptors.py::_deserialize_llm_response` expects
    (`{"content", "tool_calls", "usage": {"input_tokens", "output_tokens"}}`).

    A source platform's own "output" field is not guaranteed to already be
    shaped this way -- it can just as easily be a plain string (confirmed as
    a real case: OTel/OpenInference's `output.value` attribute is a string by
    convention). Anything already shaped like an LLM response (has "content")
    is normalized field-by-field, with Langfuse's own camelCase usage field
    names (`promptTokens`/`completionTokens`) covered alongside this
    project's own snake_case convention; anything else is wrapped wholesale
    into `content`, which is always a safe fallback since `content` is all
    `assert_path`/the replayed AIMessage genuinely need to exist.
    """
    if isinstance(response, dict) and "content" in response:
        usage = response.get("usage") or {}
        return {
            "content": response.get("content", ""),
            "tool_calls": response.get("tool_calls") or [],
            "usage": {
                "input_tokens": usage.get("input_tokens", usage.get("promptTokens", 0)),
                "output_tokens": usage.get("output_tokens", usage.get("completionTokens", 0)),
            },
        }
    return {"content": "" if response is None else str(response), "tool_calls": [], "usage": {"input_tokens": 0, "output_tokens": 0}}


def _cassette_entry(span: NormalizedSpan, occurrence: int) -> dict[str, Any]:
    key = f"{span.node}/{span.kind}/any/{occurrence}"
    entry: dict[str, Any] = {"key": key, "kind": span.kind, "node": span.node, "request": span.request, "latency_s": span.latency_s}
    if span.error is not None:
        entry["error"] = span.error
        entry["response"] = None
    elif span.kind == "llm":
        entry["response"] = _normalize_llm_response(span.response)
    else:
        entry["response"] = span.response
    if span.kind == "llm" and span.model:
        entry["model"] = span.model
    if span.kind == "tool" and span.name:
        entry["name"] = span.name
    return entry


def _build_cassette(trace: NormalizedTrace) -> Cassette:
    cassette = Cassette()
    occurrence_counts: dict[str, int] = {}
    for span in trace.spans:
        base = f"{span.node}/{span.kind}"
        occurrence = occurrence_counts.get(base, 0)
        occurrence_counts[base] = occurrence + 1
        cassette.append(_cassette_entry(span, occurrence))
    return cassette


def generate_test(
    trace: NormalizedTrace,
    *,
    target: str,
    test_name: str,
    cassette_path: str | Path,
) -> str:
    """Writes the replay cassette to `cassette_path` and returns the generated
    pytest file's source. Writing *that* file out is the caller's job (cli.py),
    so this function stays a pure string-producer and is easy to test directly
    without touching the filesystem beyond the one cassette it must produce.
    """
    save_cassette(_build_cassette(trace), cassette_path)
    target_module, target_factory = _split_target(target)

    observed_nodes: list[str] = []
    for span in trace.spans:
        if span.node not in observed_nodes:
            observed_nodes.append(span.node)

    return _TEST_TEMPLATE.render(
        test_name=test_name,
        target_module=target_module,
        target_factory=target_factory,
        needs_manual_construction=_factory_needs_manual_construction(target_module, target_factory),
        initial_input=trace.initial_input if trace.initial_input is not None else {},
        cassette_path=str(cassette_path),
        interrupted=trace.interrupted,
        observed_nodes=observed_nodes,
    )
